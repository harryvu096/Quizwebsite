  function scaleRows(rows, scale, mirror) {
    const out = [];
    for (let y = 0; y < rows.length; y++) {
      let wide = "";
      const src = mirror ? rows[y].split("").reverse().join("") : rows[y];
      for (let x = 0; x < src.length; x++) wide += src[x] === "#" ? "#".repeat(scale) : ".".repeat(scale);
      for (let k = 0; k < scale; k++) out.push(wide);
    }
    return out;
  }

  function toMask(rows) {
    const h = rows.length;
    const w = rows[0].length;
    const mask = [];
    let count = 0;
    for (let y = 0; y < h; y++) {
      const row = [];
      for (let x = 0; x < w; x++) {
        const on = rows[y][x] === "#";
        row.push(on);
        if (on) count++;
      }
      mask.push(row);
    }
    return { w: w, h: h, mask: mask, count: count };
  }

  return { ARTS: ARTS, scaleRows: scaleRows, toMask: toMask };
